const contactEmail = '';
const whatsAppNumber = '';
let activeLanguage = 'id';

function setLanguage(language) {
  activeLanguage = language;
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = translations[language][element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const value = translations[language][element.dataset.i18nPlaceholder];
    if (value) element.placeholder = value;
  });
  document.querySelectorAll('[data-language]').forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
  document.querySelector('.menu-toggle').setAttribute('aria-label', language === 'id' ? 'Buka navigasi' : 'Open navigation');
  document.querySelector('.mobile-nav').setAttribute('aria-label', language === 'id' ? 'Navigasi seluler' : 'Mobile navigation');
  document.getElementById('form-status').textContent = '';
}

document.querySelectorAll('[data-language]').forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});

const menuToggle = document.querySelector('.menu-toggle');
const mobileNav = document.querySelector('.mobile-nav');
menuToggle.addEventListener('click', () => {
  const isExpanded = menuToggle.getAttribute('aria-expanded') === 'true';
  menuToggle.setAttribute('aria-expanded', String(!isExpanded));
  mobileNav.hidden = isExpanded;
});
mobileNav.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => {
    menuToggle.setAttribute('aria-expanded', 'false');
    mobileNav.hidden = true;
  });
});

document.getElementById('contact-form').addEventListener('submit', (event) => {
  event.preventDefault();
  const status = document.getElementById('form-status');
  if (!contactEmail) {
    status.textContent = translations[activeLanguage].formEmailMissing;
    return;
  }
  const formData = new FormData(event.currentTarget);
  const body = `${formData.get('message')}\n\n${activeLanguage === 'id' ? 'Nama' : 'Name'}: ${formData.get('name')}\nEmail: ${formData.get('email')}`;
  window.location.href = `mailto:${contactEmail}?subject=${encodeURIComponent(translations[activeLanguage].emailSubject)}&body=${encodeURIComponent(body)}`;
});

if (contactEmail) {
  const emailLink = document.getElementById('email-contact');
  emailLink.href = `mailto:${contactEmail}`;
  emailLink.dataset.i18n = 'emailLink';
  emailLink.hidden = false;
}
if (whatsAppNumber) {
  const whatsAppLink = document.getElementById('whatsapp-contact');
  whatsAppLink.href = `https://wa.me/${whatsAppNumber.replace(/\D/g, '')}`;
  whatsAppLink.target = '_blank';
  whatsAppLink.rel = 'noopener noreferrer';
  whatsAppLink.dataset.i18n = 'whatsappLink';
  whatsAppLink.hidden = false;
}

document.getElementById('year').textContent = new Date().getFullYear();
